const test = require('node:test');
const assert = require('node:assert/strict');
const path = require('node:path');
const vm = require('node:vm');

const { readSource, collectFiles, normalizeEol, assertAbsent } = require('../helpers/sourceText.cjs');
const { createFakeVscode, fakeExtensionContext, withFakeVscode } = require('../helpers/fakeVscode.cjs');

/*
 * CodeXR generates two different A-Frame pages from two templates, and they do
 * NOT load the same runtimes. The XR analysis scene (xr-visualization.html) loads
 * templates/components/common/. The DOM-visualization scene
 * (dom-visualization-template.html) loads a short fixed list of runtimes and
 * nothing from common/: window.CodeXRCommonRuntime is never defined there.
 *
 * Most of the runtimes the DOM scene loads are shared with the XR scene, and that
 * is the trap. A helper hoisted out of them into common/ keeps working in the XR
 * scene - the one nearly every other suite exercises - while in the DOM scene a
 * bare call throws and the house style `root.CodeXRCommonRuntime?.fn?.(...)`
 * silently does nothing. So optional chaining is not a safe way in: for these
 * runtimes ANY use of a common/ global is functionality the DOM scene loses.
 * That is why avatar, collaboration, virtual-screen and dom-scene keep their own
 * copies of small helpers such as cloneVector (v1.2.1 audit, runtime-js/DUP-06:
 * the copies stay, on purpose).
 *
 * The runtime sources are read from a scene generated by the real DOM pipeline
 * (VisualizeDOMParser from out/), keyed by the file name the page loads them by.
 * That is the only mapping from a <script src> to its source that cannot drift:
 * multi-part runtimes arrive assembled by the production assembler, and a
 * runtime the template loads but the pipeline forgets to ship shows up too.
 */

const DOM_SCENE_TEMPLATE = 'templates/xr/html/dom-visualization-template.html';
const XR_SCENE_TEMPLATE = 'templates/xr/file/xr-visualization.html';
const COMMON_RUNTIME_FOLDER = 'templates/components/common';

// The contract itself: what the DOM scene loads, in load order (a runtime comes
// after the ones whose globals it reads; the dom-scene glue, which drives the
// collaboration runtime, comes last). `identity` is the name the rest of the
// scene knows the runtime by - the global it publishes or the A-Frame component
// the template attaches - and is the canary proving a haystack is that runtime.
const DOM_SCENE_RUNTIMES = [
    { script: 'codexrAvatarRuntime.js', identity: /\bCodeXRAvatarRuntime\b/ },
    { script: 'codexrCollaborationRuntime.js', identity: /\bCodeXRCollaborationRuntime\b/ },
    { script: 'virtualScreenRuntime.js', identity: /\bCodeXRVirtualScreenRuntime\b/ },
    { script: 'codexrMultiScreenManagerRuntime.js', identity: /codexr-multi-screen-manager/ },
    { script: 'codexrPointerPolicyRuntime.js', identity: /codexr-pointer-policy/ },
    { script: 'codexrImmersiveRigRuntime.js', identity: /codexr-immersive-rig/ },
    { script: 'codexrDomSceneCollaborationRuntime.js', identity: /\bCodeXRDomSceneCollaborationRuntime\b/ },
];

// The scene's own script (the SSE live-reload client); the pipeline resolves it.
// It runs in the same page as the runtimes, so it is held to the same rule. Its
// identity is the payload global it shares with the template's inline script,
// which tells it apart from the XR scene's live-reload client.
const SCENE_SCRIPT_PLACEHOLDER = '${scriptUri}';
const SCENE_SCRIPT_IDENTITY = /__CODEXR_DOM_HTML_PAYLOAD__/;

// Only the DOM scene loads the dom-scene glue, so this tag proves that a haystack
// is the DOM template and still holds its runtime <script> block.
const DOM_TEMPLATE_SCRIPT_BLOCK = /<script\b[^>]*\ssrc="\.\/codexrDomSceneCollaborationRuntime\.js/;

const DECISION = 'The DOM scene defines no common/ global, so every script it loads must stay self-contained. '
    + `Loading common/ there is a deliberate change, not a refactor: add the <script> to ${DOM_SCENE_TEMPLATE}, `
    + 'ship the file from VisualizeDOMParser, and update this suite in the same commit.';

const LIST_DECISION = 'DOM_SCENE_RUNTIMES is the whole runtime surface of the DOM scene, in load order. If this change is deliberate, '
    + 'update the list in the same commit and say why: an added runtime must also be shipped by VisualizeDOMParser and must not need common/.';

function withoutHtmlComments(html) {
    return html.replace(/<!--[\s\S]*?-->/g, '');
}

function scriptSources(html) {
    const markup = withoutHtmlComments(html);
    const sources = [...markup.matchAll(/<script\b[^>]*?\ssrc\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s"'>]+))/gi)]
        .map((match) => match[1] ?? match[2] ?? match[3]);

    // A tag this reader skipped would load unseen and leave the exact list below
    // green, so every <script> that carries a src must have been read, however
    // the attribute is quoted.
    const tagsWithSource = markup.match(/<script\b[^>]*\ssrc\b/gi) || [];
    assert.equal(sources.length, tagsWithSource.length, 'a <script src> tag is written in a form this suite does not read: teach scriptSources() to read it');
    return sources;
}

/** Every <script src> that is not an absolute URL, as the file name the server is asked for (no ./, no cache-buster). */
function localScriptNames(html) {
    return scriptSources(html)
        .filter((source) => !/^(?:[a-z][a-z0-9+.-]*:)?\/\//i.test(source))
        .map((source) => source.replace(/^\.\//, '').replace(/\?.*$/, ''));
}

/**
 * Prose may name the shared runtime - a comment saying why a helper is duplicated
 * is exactly what this rule invites - but code may not. Dropping whole comment
 * lines errs on the strict side: a reference sharing its line with code is kept,
 * whether the comment trails the code or the code follows a closed comment.
 */
function codeLines(source) {
    return source.split('\n')
        .filter((line) => !/^\s*(?:\/\/|\/\*|\*)/.test(line) || /\*\/\s*\S/.test(line))
        .join('\n');
}

/** The runtimes under common/ with the global each one publishes, read from the folder so the list cannot go stale. */
function commonRuntimes() {
    const runtimes = collectFiles(COMMON_RUNTIME_FOLDER, { extensions: ['.js'] }).map((posixPath) => {
        const published = /\broot\.(CodeXR\w+)\s*=(?!=)/.exec(readSource(posixPath));
        assert.ok(published, `${posixPath} does not publish a root.CodeXR* global the way its siblings do: teach this suite which global it defines`);
        return { script: path.posix.basename(posixPath), global: published[1] };
    });

    // Anchor: a derived list that silently lost the shared runtime would turn every guard below into a no-op.
    assert.deepEqual(
        runtimes.filter((runtime) => runtime.script === 'codexrCommonRuntime.js').map((runtime) => runtime.global),
        ['CodeXRCommonRuntime'],
        `${COMMON_RUNTIME_FOLDER} no longer holds codexrCommonRuntime.js publishing CodeXRCommonRuntime: retarget this suite to wherever the shared runtime went`,
    );
    return runtimes;
}

/** Matches a common/ runtime by file name or by global, in any spelling (they differ only in case today). */
function commonReferencePattern(runtimes) {
    const names = runtimes.flatMap((runtime) => [runtime.script.replace(/\.js$/, ''), runtime.global]);
    const escaped = [...new Set(names)].map((name) => name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'));
    return new RegExp(`(?:${escaped.join('|')})`, 'i');
}

let generatedDomScene;

/** The files of one generated DOM scene (name -> LF text). The pipeline runs once for the whole suite. */
function generateDomScene() {
    if (!generatedDomScene) {
        generatedDomScene = runDomPipeline();
    }
    return generatedDomScene;
}

async function runDomPipeline() {
    const fake = createFakeVscode();
    const context = fakeExtensionContext();
    // The parser narrates every step on the console; keep that out of the shared
    // test output. A real failure still surfaces, as the rejection of this call.
    const silenced = ['debug', 'log', 'info', 'warn', 'error'];
    const originals = silenced.map((method) => console[method]);
    silenced.forEach((method) => {
        console[method] = () => {};
    });

    try {
        const files = await withFakeVscode(fake, async ({ requireOut }) => {
            const { VisualizeDOMParser } = requireOut('code_analysis/engine/parsers/visualizeDOMParser.js');
            return new VisualizeDOMParser(context).processHTMLTemplates({
                htmlContent: '<!DOCTYPE html><html><body><p>contract probe</p></body></html>',
                fileName: 'probe.html',
                filePath: path.join(context.storagePath, 'probe.html'),
            });
        });
        return new Map([...files].map(([name, content]) => [name, normalizeEol(content)]));
    } finally {
        silenced.forEach((method, index) => {
            console[method] = originals[index];
        });
        context.cleanup();
    }
}

test('the DOM scene template loads a fixed, ordered list of CodeXR runtimes, then the scene script, and no other local script', () => {
    const loaded = localScriptNames(readSource(DOM_SCENE_TEMPLATE));

    assert.deepEqual(
        loaded,
        [...DOM_SCENE_RUNTIMES.map((runtime) => runtime.script), SCENE_SCRIPT_PLACEHOLDER],
        `${LIST_DECISION}\nLocal scripts the template loads now: ${JSON.stringify(loaded)}`,
    );
});

test('the DOM scene template loads nothing from templates/components/common/, which the XR scene template does load', () => {
    const common = commonRuntimes();

    // Control: the XR scene loads the shared runtime through the very tag shape
    // this suite reads, so its absence below is not a blind spot of the reader.
    assert.ok(
        localScriptNames(readSource(XR_SCENE_TEMPLATE)).includes('codexrCommonRuntime.js'),
        'the XR scene template is expected to load codexrCommonRuntime.js as a local <script src>',
    );

    // Neither a <script src> nor the inline scripts of the template may name a
    // common/ runtime, by file or by global.
    assertAbsent(withoutHtmlComments(readSource(DOM_SCENE_TEMPLATE)), commonReferencePattern(common), {
        canary: DOM_TEMPLATE_SCRIPT_BLOCK,
        message: DECISION,
    });
});

test('a generated DOM scene ships every local script its page loads, and ships no script the page does not load', async () => {
    const files = await generateDomScene();
    const page = files.get('index.html');
    assert.ok(page, 'the DOM pipeline emits the page as index.html');
    const loaded = localScriptNames(page);

    const resolvedTemplate = localScriptNames(readSource(DOM_SCENE_TEMPLATE))
        .map((name, index) => (name === SCENE_SCRIPT_PLACEHOLDER ? loaded[index] : name));
    assert.deepEqual(loaded, resolvedTemplate, 'processing the template only resolves placeholders: it neither adds, drops nor reorders a script');

    assert.deepEqual(
        loaded.filter((name) => !files.has(name)),
        [],
        'every local <script src> of the page must be a file the DOM pipeline writes next to it, or the browser gets a 404',
    );
    assert.deepEqual(
        [...files.keys()].filter((name) => name.endsWith('.js') && !loaded.includes(name)),
        [],
        'the DOM pipeline ships a script the page never loads: either the template lost a <script> or the scene carries dead weight',
    );
});

test('no script the DOM scene loads, runtime or scene script, references a global published by templates/components/common/', async () => {
    const files = await generateDomScene();
    const commonReference = commonReferencePattern(commonRuntimes());

    // The scene script has no fixed name in the template: take the one the page
    // loads where the template holds the placeholder.
    const placeholderIndex = localScriptNames(readSource(DOM_SCENE_TEMPLATE)).indexOf(SCENE_SCRIPT_PLACEHOLDER);
    assert.notEqual(placeholderIndex, -1, `${DOM_SCENE_TEMPLATE} no longer loads its scene script through ${SCENE_SCRIPT_PLACEHOLDER}`);
    const sceneScript = localScriptNames(files.get('index.html') || '')[placeholderIndex];
    assert.ok(sceneScript, 'the generated page loads no script where the template holds the scene-script placeholder');

    for (const runtime of [...DOM_SCENE_RUNTIMES, { script: sceneScript, identity: SCENE_SCRIPT_IDENTITY }]) {
        const source = files.get(runtime.script);
        assert.ok(source, `${runtime.script} is loaded by the DOM scene but the DOM pipeline does not ship it`);

        // A haystack holding only some parts of a multi-part runtime would make the
        // guard vacuous for the rest. A complete runtime compiles as the classic
        // script the page loads it as; a truncated one does not close its wrapper.
        assert.doesNotThrow(
            () => new vm.Script(source, { filename: runtime.script }),
            `${runtime.script} as shipped to the DOM scene is not a complete script`,
        );

        assertAbsent(codeLines(source), commonReference, {
            canary: runtime.identity,
            message: `${runtime.script} uses a common/ runtime. ${DECISION}`,
        });
    }
});

test('the script reader sees a local <script src> however it is written, and skips CDN scripts and commented-out tags', () => {
    const html = [
        '<script src="https://aframe.io/releases/1.7.1/aframe.min.js"></script>',
        '<script src="//cdn.example/protocol-relative.js"></script>',
        '<!-- <script src="./commentedOut.js"></script> -->',
        '<script nonce="${nonce}" src="./doubleQuoted.js?v=${nonce}"></script>',
        "<SCRIPT SRC='./singleQuoted.js'></SCRIPT>",
        '<script src=./unquoted.js></script>',
        '<script data-src="./notASource.js" type="application/json">{}</script>',
        '<script>inline();</script>',
    ].join('\n');

    assert.deepEqual(localScriptNames(html), ['doubleQuoted.js', 'singleQuoted.js', 'unquoted.js']);
});

test('the self-containment guard trips on a reference in code, whatever its style, and ignores one in a comment', () => {
    const common = commonRuntimes();
    const commonReference = commonReferencePattern(common);
    const canary = /codexr-probe/;
    const selfContained = "AFRAME.registerComponent('codexr-probe', {});";
    const guard = (source) => assertAbsent(codeLines(source), commonReference, { canary });

    guard(selfContained);
    guard(`${selfContained}\n  // Not shared through CodeXRCommonRuntime: the DOM scene never loads common/.`);
    guard(`${selfContained}\n/**\n * window.CodeXRCommonRuntime is undefined in the DOM scene.\n */`);

    // The canary check throws an AssertionError too, so only the absence check
    // itself counts as the guard tripping.
    const trippedOnTheReference = (error) => error instanceof assert.AssertionError && error.operator === 'doesNotMatch';

    for (const runtime of common) {
        const references = [
            `root.${runtime.global}?.faceCameraYaw?.(entity, scene);`,
            `var shared = window['${runtime.global}'] || {};`,
            `${runtime.global}.createTooltip({});`,
            `root.${runtime.global}.hideTooltip(card); // a trailing comment does not hide the code before it`,
            `/* a closed comment does not hide the code after it */ root.${runtime.global}.hideTooltip(card);`,
        ];
        for (const reference of references) {
            assert.throws(() => guard(`${selfContained}\n${reference}`), trippedOnTheReference, `the guard missed: ${reference}`);
        }
    }

    // The canary is what keeps the guard honest once a runtime moves or empties out.
    assert.throws(() => guard(''), (error) => error instanceof assert.AssertionError && error.operator === 'match' && /canary not found/.test(error.message));
});
